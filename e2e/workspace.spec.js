test('copy feedback reports success and permission failure', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await go(page, 'json'); await input(page).fill('{"id":9223372036854775807}')
  await page.getByRole('button', { name: '格式化', exact: true }).click(); await complete(page)
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.locator('.app-toast')).toContainText('已复制')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('9223372036854775807')
  await page.evaluate(() => { navigator.clipboard.writeText = () => Promise.reject(new DOMException('denied', 'NotAllowedError')) })
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await expect(page.locator('.app-toast')).toContainText('复制失败')
})

test('a cancelled worker cannot replace newer input and processing can resume', async ({ page }) => {
  const blocked = []
  await page.route('**/*processor*', route => { blocked.push(route) })
  await go(page, 'json'); await input(page).fill('{"old":true}')
  await page.getByRole('button', { name: '格式化', exact: true }).click()
  await expect(page.locator('.workspace-status')).toContainText('处理中')
  await page.getByRole('button', { name: '取消处理', exact: true }).click()
  await expect(page.locator('.workspace-status')).toContainText('已取消')
  await input(page).fill('{"new":true}')
  await page.unroute('**/*processor*')
  for (const route of blocked) await route.abort().catch(() => {})
  await page.getByRole('button', { name: '格式化', exact: true }).click(); await complete(page)
  await expect(output(page)).toContainText('new'); await expect(output(page)).not.toContainText('old')
})

