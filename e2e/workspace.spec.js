import { test, expect } from '@playwright/test'

const input = page => page.getByRole('textbox', { name: 'JSON 输入', exact: true })
const output = page => page.getByRole('textbox', { name: '处理结果', exact: true })
async function go(page, path) { await page.goto(`./#/${path}`); await expect(page.locator('.tool-workspace')).toBeVisible() }
async function tool(page, name) {
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox', { name: '搜索工具或当前操作' }).fill(name)
  await page.locator('.command-results').getByRole('option').filter({ hasText: name }).first().click()
}
async function complete(page) { await expect(page.locator('.workspace-status')).toContainText('处理完成') }

test('JSON exact data, safe rendering, download, stale result and tree queries', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await go(page, 'json')
  await input(page).fill('{"id":9223372036854775807,"html":"<b>hello</b>","a.b":[false]}')
  await page.getByRole('button', { name: '格式化', exact: true }).click(); await complete(page)
  await expect(output(page)).toContainText('9223372036854775807')
  await expect(output(page)).toContainText('<b>hello</b>')
  await expect(output(page).locator('b')).toHaveCount(0)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '下载', exact: true }).click()])
  const stream = await download.createReadStream(); const chunks = []; for await (const chunk of stream) chunks.push(chunk)
  expect(Buffer.concat(chunks).toString()).toContain('9223372036854775807')
  await page.getByRole('button', { name: '树视图', exact: true }).click()
  await expect(page.locator('.tree-panel')).toContainText('9223372036854775807')
  await page.getByLabel('路径查询', { exact: true }).fill('$["a.b"][0]')
  await expect(page.getByRole('button', { name: '复制', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '查询', exact: true }).click(); await complete(page)
  await expect(output(page)).toContainText('false')
  await input(page).fill('{"invalid":}')
  await page.getByRole('button', { name: '格式化', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('第 1 行')
  await expect(page.getByRole('button', { name: '复制', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '定位错误' }).click()
  await expect(input(page)).toBeFocused()
  expect(errors).toEqual([])
})

