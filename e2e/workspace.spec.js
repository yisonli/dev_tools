  await expect(page.locator('#json-input .cm-searchMatch')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await input(page).press('Control+End')
  await page.keyboard.insertText(' ')
  await tool(page, 'Base64'); await tool(page, 'JSON')
